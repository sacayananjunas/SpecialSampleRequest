// Generates db/seed.sql from the realistic demo data in scripts/seed-source.
// Run: node scripts/generate-seed.js   (only needed if you change the demo data)
// The output is idempotent (ON CONFLICT DO NOTHING) and uses timestamps relative to now().
import { writeFileSync } from 'node:fs';
import bcrypt from 'bcryptjs';
import { TEST_CATALOG, PACKAGES } from './seed-source/testCatalog.js';
import { SPECS, SPEC_OPTIONS } from './seed-source/specs.js';
import { PROCESS_UNITS } from './seed-source/plantUnits.js';
import { INSTRUMENTS } from './seed-source/instruments.js';
import { TREND_SERIES, trendData } from './seed-source/trends.js';
import { generateMockRequests } from './seed-source/requests.js';

const NOW = Date.now();
const q = (v) => (v === null || v === undefined || v === '' ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === null || v === undefined || v === '' ? 'NULL' : Number(v));
const b = (v) => (v ? 'true' : 'false');
const arr = (a) => `ARRAY[${a.map(q).join(', ')}]::text[]`;
const ts = (iso) => `(now() - interval '${Math.round((NOW - new Date(iso).getTime()) / 1000)} seconds')`;

const DEMO_PW = bcrypt.hashSync('Demo1234!', 10);
const TEST_PW = bcrypt.hashSync('Test1234!', 10);

const USERS = [
  ['test@petrosync.com', TEST_PW, 'Test User', 'requester', 'Quality Assurance', 'QA Engineer', 'Bataan Refinery'],
  ['maya@petrosync.com', DEMO_PW, 'Maya Santos', 'requester', 'Process Engineering', 'Process Engineer', 'Bataan Refinery'],
  ['carlos@petrosync.com', DEMO_PW, 'Carlos Mendoza', 'requester', 'Operations', 'Shift Supervisor', 'Bataan Refinery'],
  ['priya@petrosync.com', DEMO_PW, 'Priya Nair', 'requester', 'Quality Assurance', 'QA Specialist', 'Bataan Refinery'],
  ['liam@petrosync.com', DEMO_PW, "Liam O'Connor", 'requester', 'Trading & Supply', 'Crude Trader', 'Batangas Terminal'],
  ['rosa@petrosync.com', DEMO_PW, 'Rosa Villanueva', 'requester', 'Technical Services', 'Technical Services Engineer', 'Bataan Refinery'],
  ['kenji@petrosync.com', DEMO_PW, 'Kenji Watanabe', 'requester', 'R&D', 'R&D Chemist', 'Bataan Refinery'],
  ['daniel@petrosync.com', DEMO_PW, 'Daniel Reyes', 'analyst', 'Central Laboratory', 'Senior Lab Analyst', 'Bataan Refinery'],
  ['ana@petrosync.com', DEMO_PW, 'Ana Cruz', 'analyst', 'Central Laboratory', 'Lab Analyst', 'Bataan Refinery'],
  ['mark@petrosync.com', DEMO_PW, 'Mark Tan', 'analyst', 'Central Laboratory', 'Lab Analyst', 'Bataan Refinery'],
  ['aisha@petrosync.com', DEMO_PW, 'Dr. Aisha Rahman', 'supervisor', 'Central Laboratory', 'Laboratory Supervisor', 'Bataan Refinery'],
];
const userId = (name) => `(SELECT id FROM users WHERE full_name = ${q(name)} LIMIT 1)`;

const out = [];
const add = (s) => out.push(s);
add('-- PetroSync seed data. Generated by scripts/generate-seed.js. Safe to run repeatedly.');
add('BEGIN;');

add('\n-- Users (demo password Demo1234!, test user Test1234!)');
for (const u of USERS) add(`INSERT INTO users (email, password_hash, full_name, role, department, title, site) VALUES (${u.map(q).join(', ')}) ON CONFLICT (email) DO NOTHING;`);

add('\n-- Process units and sampling points');
PROCESS_UNITS.forEach((u, i) => add(`INSERT INTO process_units (id, name, full_name, points, sort_order) VALUES (${q(u.id)}, ${q(u.name)}, ${q(u.full)}, ${arr(u.points)}, ${i}) ON CONFLICT (id) DO NOTHING;`));

add('\n-- Test catalog');
TEST_CATALOG.forEach((t, i) =>
  add(`INSERT INTO tests (id, name, method, unit, range_min, range_max, decimals, sample_types, min_volume, container, tat_hours, price, instrument, notes, sort_order) VALUES (${q(t.id)}, ${q(t.name)}, ${q(t.method)}, ${t.unit ? q(t.unit) : "''"}, ${t.range[0]}, ${t.range[1]}, ${t.dp}, ${arr(t.types)}, ${q(t.minVol)}, ${q(t.container)}, ${t.tat}, ${t.price}, ${q(t.instrument)}, ${q(t.notes)}, ${i}) ON CONFLICT (id) DO NOTHING;`),
);

add('\n-- Specifications and limits');
SPEC_OPTIONS.forEach((o, i) => add(`INSERT INTO specs (id, name, short_name, label, sort_order) VALUES (${q(o.id)}, ${q(SPECS[o.id].name)}, ${q(SPECS[o.id].short)}, ${q(o.label)}, ${i}) ON CONFLICT (id) DO NOTHING;`));
for (const [sid, s] of Object.entries(SPECS))
  for (const [tid, l] of Object.entries(s.limits))
    add(`INSERT INTO spec_limits (spec_id, test_id, min_value, max_value, nominal) VALUES (${q(sid)}, ${q(tid)}, ${n(l.min)}, ${n(l.max)}, ${n(l.nominal)}) ON CONFLICT (spec_id, test_id) DO NOTHING;`);

add('\n-- Test packages');
PACKAGES.forEach((p, i) => {
  add(`INSERT INTO packages (id, name, product, spec_id, sort_order) VALUES (${q(p.id)}, ${q(p.name)}, ${q(p.product)}, ${q(p.spec)}, ${i}) ON CONFLICT (id) DO NOTHING;`);
  p.tests.forEach((t, k) => add(`INSERT INTO package_tests (package_id, test_id, order_index) VALUES (${q(p.id)}, ${q(t)}, ${k}) ON CONFLICT DO NOTHING;`));
});

add('\n-- Instruments');
INSTRUMENTS.forEach((x, i) => add(`INSERT INTO instruments (id, name, model, status, detail, sort_order) VALUES (${q(x.id)}, ${q(x.name)}, ${q(x.model)}, ${q(x.status)}, ${q(x.detail)}, ${i}) ON CONFLICT (id) DO NOTHING;`));

add('\n-- Property trend series (60 days of daily results)');
TREND_SERIES.forEach((s, i) => {
  add(`INSERT INTO trend_series (id, label, unit, method, limit_value, limit_label, is_min, decimals, sort_order) VALUES (${q(s.id)}, ${q(s.label)}, ${s.unit ? q(s.unit) : "''"}, ${q(s.method)}, ${s.limit}, ${q(s.limitLabel)}, ${b(s.min)}, ${s.dp}, ${i}) ON CONFLICT (id) DO NOTHING;`);
  trendData(s.id).forEach((d, k, all) => add(`INSERT INTO property_readings (series_id, reading_date, value) VALUES (${q(s.id)}, current_date - ${all.length - 1 - k}, ${d.value}) ON CONFLICT DO NOTHING;`));
});

add('\n-- Sample requests');
const reqs = generateMockRequests(NOW);
for (const r of reqs) {
  const requester = USERS.find((u) => u[2] === r.requester.name);
  add(
    `INSERT INTO requests (id, requester_id, requester_name, department, created_at, site, unit_id, sampling_point, batch, cost_center, product, num_samples, sampled_at, sampled_by, volume, container, package_id, package_name, purpose, spec_id, flam_class, h2s, h2s_ppm, pressurized, norm, storage, retain, instructions, priority, attachments, status, status_at, due_at, retest_of) VALUES (` +
      [q(r.id), userId(requester[2]), q(r.requester.name), q(r.requester.dept), ts(r.createdAt), q(r.site), q(r.unit), q(r.point), q(r.batch), q(r.costCenter), q(r.product), r.numSamples, ts(r.sampledAt), q(r.sampledBy), q(r.volume), q(r.container), q(r.packageId), q(r.packageName), q(r.purpose), q(r.spec), q(r.flamClass), b(r.h2s), n(r.h2sPpm), b(r.pressurized), b(r.norm), q(r.storage), b(r.retain), q(r.instructions), q(r.priority), `${q(JSON.stringify(r.attachments))}::jsonb`, q(r.status), ts(r.statusAt), ts(r.dueAt), q(r.retestOf)].join(', ') +
      ') ON CONFLICT (id) DO NOTHING;',
  );
  r.tests.forEach((t, k) => add(`INSERT INTO request_tests (request_id, test_id, order_index) VALUES (${q(r.id)}, ${q(t)}, ${k}) ON CONFLICT DO NOTHING;`));
  for (const [tid, res] of Object.entries(r.results))
    add(`INSERT INTO results (request_id, test_id, value, entered_by, entered_by_name, entered_at) VALUES (${q(r.id)}, ${q(tid)}, ${res.value}, ${userId(res.by)}, ${q(res.by)}, ${ts(res.at)}) ON CONFLICT DO NOTHING;`);
  r.custody.forEach((c, k) => add(`INSERT INTO custody_events (id, request_id, at, by_name, by_role, action, note) VALUES (${q(`${r.id}-e${k}`)}, ${q(r.id)}, ${ts(c.at)}, ${q(c.by)}, ${q(c.role)}, ${q(c.action)}, ${q(c.note)}) ON CONFLICT (id) DO NOTHING;`));
  r.comments.forEach((c, k) => add(`INSERT INTO comments (id, request_id, user_id, by_name, by_role, body, at) VALUES (${q(`${r.id}-c${k}`)}, ${q(r.id)}, ${userId(c.by)}, ${q(c.by)}, ${q(c.role)}, ${q(c.text)}, ${ts(c.at)}) ON CONFLICT (id) DO NOTHING;`));
  r.issues.forEach((x, k) => add(`INSERT INTO issues (id, request_id, type, note, by_name, at) VALUES (${q(`${r.id}-i${k}`)}, ${q(r.id)}, ${q(x.type)}, ${q(x.note)}, ${q(x.by)}, ${ts(x.at)}) ON CONFLICT (id) DO NOTHING;`));
}

add("\n-- Keep the sample-ID sequence ahead of existing requests");
add("SELECT setval('request_seq', GREATEST((SELECT COALESCE(MAX(substring(id from 9)::int), 100) FROM requests), (SELECT last_value FROM request_seq)));");
add('COMMIT;');

writeFileSync(new URL('../db/seed.sql', import.meta.url), out.join('\n') + '\n');
console.log(`db/seed.sql written: ${USERS.length} users, ${TEST_CATALOG.length} tests, ${PACKAGES.length} packages, ${reqs.length} requests, ${INSTRUMENTS.length} instruments.`);
